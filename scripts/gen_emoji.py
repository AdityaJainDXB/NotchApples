def main(path):
    out, seen = [], set()
    for line in open(path, encoding='utf-8'):
        m = re.match(r'^([0-9A-F ]+?)\s*; fully-qualified\s*# (\S+) E([0-9.]+) (.+)$', line.strip())
        if not m: continue
        cps, emoji, ver, name = m.groups()
        if float(ver) > MAX_VERSION or 'skin tone' in name or emoji in seen: continue
        seen.add(emoji)
        name = name.lower()
        words = ' '.join(w for key, w in ALIASES if (name == key[1:] if key.startswith('=') else key in name)).split()
        extra = ' '.join(dict.fromkeys(words))
        out.append(f'{emoji}|{name}|{extra}')
    out += SYMBOLS.split('\n')
    text = '\n'.join(out)
    assert '"""' not in text and '\\' not in text
    open('NotchApple/Core/EmojiData.swift', 'w', encoding='utf-8').write(
        '// Generated by scripts/gen_emoji.py from Unicode emoji-test.txt (Unicode License). Don\'t edit by hand.\n'
        'enum EmojiData {\n    static let raw = """\n' + text + '\n"""\n}\n')
    open('NotchWindows/src/js/services/emojidata.js', 'w', encoding='utf-8').write(
        '// Generated by scripts/gen_emoji.py from Unicode emoji-test.txt (Unicode License). Don\'t edit by hand.\n'
        'export const RAW = `' + text + '`;\n')
    print(len(out), 'entries')

main(sys.argv[1])
