#!/usr/bin/env python3
"""Builds the emoji picker data for the Mac and Windows apps from Unicode's emoji-test.txt.
   curl -o /tmp/emoji-test.txt https://unicode.org/Public/emoji/latest/emoji-test.txt
   python3 scripts/gen_emoji.py /tmp/emoji-test.txt
Keeps emoji up to Unicode Emoji 14.0 (so they show on current macOS and Windows 11), drops skin-tone variants,
and adds a few everyday search words ("love" finds hearts). One line per entry: emoji|name|extra words."""
import re, sys

MAX_VERSION = 14.0
ALIASES = [  # name contains -> extra words (a leading = means the whole name)
    ("heart", "love"), ("grinning", "happy"), ("smiling", "happy smile"), ("joy", "lol laugh"), ("rolling on the floor", "lol rofl"),
    ("thumbs up", "ok yes like good approve"), ("thumbs down", "no bad dislike"), ("=fire", "hot lit"), ("party popper", "celebrate congrats tada"),
    ("clapping", "applause bravo"), ("folded hands", "pray thanks please"), ("check mark", "tick done yes correct"), ("cross mark", "no wrong x"),
    ("loudly crying", "sob"), ("crying", "sad tear"), ("pile of poo", "poop"), ("=rocket", "launch ship"), ("=eyes", "look see"), ("=sparkles", "magic new shiny"),
    ("red heart", "love"), ("face with tears of joy", "lol laugh"), ("=skull", "dead"), ("waving hand", "hello hi bye"), ("light bulb", "idea"),
    ("=warning", "caution"), ("money", "cash"), ("birthday cake", "bday"), ("=thinking", "hmm"), ("winking", "flirt"), ("sleeping", "tired zzz"),
    ("angry", "mad"), ("pouting", "mad"), ("=sun", "sunny"), ("rainbow", "pride"), ("hundred points", "100 perfect"), ("=bug", "insect"),
]
