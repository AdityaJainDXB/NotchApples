// Writes friends-vectors.json: fixed inputs and the outputs friendscrypto.js produces for them. The Swift app and the JS
// client check the same file, so the two implementations can't drift apart. Run only when the protocol itself changes:
//   node server/room-relay/test/make-vectors.mjs
import { writeFileSync } from 'node:fs';
import { loadModule } from '../../../NotchWindows/tests/load.mjs';
const F = await loadModule('services/friendscrypto.js');

const seed = (n) => Uint8Array.from({ length: 32 }, (_, i) => (n * 31 + i * 7) & 255);
const alice = await F.identityFromSeeds(seed(1), seed(2)), bob = await F.identityFromSeeds(seed(3), seed(4));
const boxB = await F.boxOf('BOBCODE123');
const body = { t: 'msg', id: '6f1d2c3a-0000-4000-8000-000000000001', ts: 1790000000000, text: 'Hello Bob ✓ "quoted" \\ / <b>' };
const ts = '1790000000000', reqBody = '{"to":"abc"}';
const out = {
  note: 'Generated by make-vectors.mjs from friendscrypto.js. Seeds are 32 bytes (base64url).',
  codes: await Promise.all(['0123456789', 'ABCDEFGHJK', 'ZZZZZZZZZZ'].map(async (code) => ({ code, box: await F.boxOf(code) }))),
  identities: await Promise.all([[1, 2], [3, 4]].map(async ([a, b]) => { const id = await F.identityFromSeeds(seed(a), seed(b));
    return { signSeed: F.b64u(id.signSeed), dhSeed: F.b64u(id.dhSeed), signPub: F.b64u(id.signPub), dhPub: F.b64u(id.dhPub), fingerprint: F.b64u(await F.fingerprint(id.signPub, id.dhPub)) }; })),
  auth: { method: 'POST', path: '/f/send', ts, body: reqBody, message: await F.authMessage('POST', '/f/send', ts, reqBody), header: await F.authHeader(alice, 'POST', '/f/send', ts, reqBody) },
  tokenHash: { token: F.b64u(seed(9)), hash: await F.tokenHash(F.b64u(seed(9))) },
  seal: { sender: 0, recipient: 1, recipientBox: boxB, kind: 'msg', body, bodyText: JSON.stringify(body),
    ephSeed: F.b64u(seed(5)), nonce: F.b64u(seed(6).slice(0, 12)),
    blob: await F.seal(alice, { box: boxB, dh: bob.dhPub }, 'msg', body, { ephSeed: seed(5), nonce: seed(6).slice(0, 12) }) },
  safetyNumber: await F.safetyNumber(alice, bob),
};
writeFileSync(new URL('./friends-vectors.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log('wrote friends-vectors.json');
