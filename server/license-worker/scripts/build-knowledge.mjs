// Builds src/knowledge.js: everything the website's "Ask" helper may use to answer, as one string for the AI's prompt.
// Sources: the FAQ the helper already uses, the feature list and the how-to guides. Run it again after those change:
//   node server/license-worker/scripts/build-knowledge.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const plain = (md) => md
  .replace(/!\[[^\]]*\]\([^)]*\)/g, '')                 // images
  .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')               // links keep their text
  .replace(/<\/?[a-z][^>]*>/gi, '')                      // html (kbd, details…)
  .replace(/\|\s*-{2,}[^\n]*\n/g, '')                    // table rules
  .replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();
const faq = JSON.parse(readFileSync(here('../../../web/assets/faq.json'), 'utf8'));
const parts = [
  '## Frequently asked questions (the most trusted source; prices and tiers here win over anything else)\n' + faq.map((e) => `Q: ${e.q}\nA: ${e.a}`).join('\n\n'),
  '## Features, module by module\n' + plain(readFileSync(here('../../../docs/FEATURES.md'), 'utf8')),
  '## How-to guides\n' + plain(readFileSync(here('../../../docs/GUIDES.md'), 'utf8')),
];
const text = parts.join('\n\n');
writeFileSync(here('../src/knowledge.js'), '// Generated by scripts/build-knowledge.mjs: do not edit.\nexport default ' + JSON.stringify(text) + ';\n');
console.log(`knowledge.js: ${text.length} characters`);
